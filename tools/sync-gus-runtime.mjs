#!/usr/bin/env node
/**
 * Vendored GUS runtime: a pinned, verifiable copy of the local-inference bridge from
 * iSyCode Móvil (https://github.com/DannyBaanks/iSyCodeMovil). Engine, not app: only the
 * allowlisted files below are copied, byte for byte.
 *
 *   node tools/sync-gus-runtime.mjs --from <40-hex SHA> [--source <git dir>]   write the snapshot
 *   node tools/sync-gus-runtime.mjs --check [--source <git dir>]               regenerate the pinned SHA
 *                                                                              in a temp dir and compare
 *   node tools/sync-gus-runtime.mjs --verify                                   offline: files match manifest
 *
 * The pin only changes with an explicit --from. There is no "latest" and no HEAD.
 * Never edit vendor/gus-runtime by hand: fix upstream, then move the pin (see README there).
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const UPSTREAM_REPO = "https://github.com/DannyBaanks/iSyCodeMovil";
/** Upstream path → vendored path (relative to the vendor dir). Mirrors upstream layout. */
export const ALLOWLIST = [
  "Sources/Model/GUSLlamaBridge.c",
  "Sources/Model/GUSLlamaBridge.h",
  "scripts/build-llama-xcframework.sh",
];
/** What the bridge may include. A new local dependency upstream must be a conscious allowlist change. */
const ALLOWED_INCLUDES = new Set([
  "GUSLlamaBridge.h", "llama/llama.h", "stdatomic.h", "pthread.h", "stdbool.h", "stdio.h",
  "stdlib.h", "string.h", "time.h", "stdint.h", "stddef.h",
]);
const MANIFEST = "VENDOR.json";
const README = "README.md";
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const DEFAULT_DEST = join(ROOT, "vendor", "gus-runtime");

export class SyncError extends Error {}

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");
const git = (cwd, ...args) => execFileSync("git", args, { cwd, stdio: ["ignore", "pipe", "pipe"] });

function requireSha(value) {
  if (!/^[0-9a-f]{40}$/.test(value ?? "")) throw new SyncError(`the pin must be a full 40-hex commit SHA, not ${JSON.stringify(value)}`);
  return value;
}

/** A local clone of upstream, or a fresh partial clone of the public repository. */
function openSource(source, commit) {
  if (source) return { dir: source, cleanup: () => {} };
  const dir = mkdtempSync(join(tmpdir(), "gus-upstream-"));
  git(dir, "init", "-q");
  git(dir, "fetch", "-q", "--depth=1", "--filter=blob:none", UPSTREAM_REPO, commit);
  return { dir, cleanup: () => rmSync(dir, { recursive: true, force: true }) };
}

/** Reads the allowlisted files at exactly `commit` (git objects, not the working tree). */
export function readUpstream(commit, source = null) {
  requireSha(commit);
  const { dir, cleanup } = openSource(source, commit);
  try {
    let resolved;
    try {
      resolved = git(dir, "rev-parse", "--verify", `${commit}^{commit}`).toString().trim();
    } catch {
      throw new SyncError(`commit ${commit} not found upstream`);
    }
    if (resolved !== commit) throw new SyncError(`upstream resolved ${commit} to ${resolved}`);
    const files = new Map();
    for (const path of ALLOWLIST) {
      try {
        files.set(path, git(dir, "show", `${commit}:${path}`));
      } catch {
        throw new SyncError(`unexpected upstream layout: ${path} is missing at ${commit}`);
      }
    }
    checkIncludes(files);
    return files;
  } finally {
    cleanup();
  }
}

function checkIncludes(files) {
  for (const [path, buf] of files) {
    if (!/\.[ch]$/.test(path)) continue;
    for (const m of buf.toString("utf8").matchAll(/^\s*#\s*include\s*[<"]([^>"]+)[>"]/gm)) {
      if (!ALLOWED_INCLUDES.has(m[1])) {
        throw new SyncError(`unexpected upstream layout: ${path} now includes ${m[1]}; review and extend the allowlist on purpose`);
      }
    }
  }
}

function llamaCommit(files) {
  const script = files.get("scripts/build-llama-xcframework.sh")?.toString("utf8") ?? "";
  const m = script.match(/LLAMA_COMMIT="([0-9a-f]{40})"/);
  if (!m) throw new SyncError("unexpected upstream layout: build-llama-xcframework.sh has no LLAMA_COMMIT");
  return m[1];
}

export function manifestFor(commit, files, syncedAt) {
  return {
    note: "GENERATED by tools/sync-gus-runtime.mjs. Do not edit files in this directory by hand.",
    upstream: { repo: UPSTREAM_REPO, commit },
    synced_at: syncedAt,
    llama_cpp_commit: llamaCommit(files),
    files: ALLOWLIST.map((path) => ({ source: path, dest: path, bytes: files.get(path).length, sha256: sha256(files.get(path)) })),
  };
}

const readmeText = (m) => `# Vendored GUS runtime (GENERATED — do not edit)

Pinned copy of the local-inference bridge from [iSyCode Móvil](${m.upstream.repo}).

- Upstream commit: \`${m.upstream.commit}\`
- llama.cpp commit (from the build script): \`${m.llama_cpp_commit}\`
- Files and sha256: \`${MANIFEST}\`

Only the engine is shared, not the app: no UI, catalog, crash diagnostics or iSyCode JNI glue.
TamagotchIA's own glue lives outside this directory.

## Changing it

1. Fix or change the bridge **upstream** in iSyCode Móvil and get it merged and tested there.
2. Pick the new SHA on purpose (never "latest").
3. \`node tools/sync-gus-runtime.mjs --from <SHA>\`
4. Review the diff, run \`npm test\` and the native smoke, and commit the pin update.

CI regenerates this directory from the pinned SHA and fails on any difference.
`;

/** Writes the snapshot into `dest`, which the script owns entirely. Touches nothing else. */
export function sync({ commit, source = null, dest = DEFAULT_DEST, syncedAt = new Date().toISOString() }) {
  const files = readUpstream(commit, source);
  const manifest = manifestFor(commit, files, syncedAt);
  rmSync(dest, { recursive: true, force: true });
  for (const path of ALLOWLIST) {
    const out = join(dest, path);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, files.get(path));
  }
  writeFileSync(join(dest, MANIFEST), JSON.stringify(manifest, null, 2) + "\n");
  writeFileSync(join(dest, README), readmeText(manifest));
  return manifest;
}

function listFiles(dir, prefix = "") {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? listFiles(join(dir, e.name), `${prefix}${e.name}/`) : [`${prefix}${e.name}`]);
}

/** Offline: every vendored file matches the manifest hash and nothing extra is present. */
export function verify(dest = DEFAULT_DEST) {
  const problems = [];
  const manifestPath = join(dest, MANIFEST);
  if (!existsSync(manifestPath)) return [`${MANIFEST} is missing`];
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  requireSha(manifest.upstream?.commit);
  const expected = new Set([MANIFEST, README, ...manifest.files.map((f) => f.dest)]);
  for (const f of manifest.files) {
    const path = join(dest, f.dest);
    if (!existsSync(path)) { problems.push(`${f.dest} is missing`); continue; }
    if (sha256(readFileSync(path)) !== f.sha256) problems.push(`${f.dest} was modified (sha256 differs from ${MANIFEST})`);
  }
  // .build/ is the gitignored llama.xcframework output of the vendored build script, not source.
  for (const extra of listFiles(dest).filter((p) => !expected.has(p) && !p.startsWith(".build/"))) problems.push(`${extra} is not part of the snapshot`);
  if (existsSync(join(dest, README)) && readFileSync(join(dest, README), "utf8") !== readmeText(manifest)) {
    problems.push(`${README} was modified`);
  }
  return problems;
}

/** Regenerates the pinned SHA in a temp dir and compares every byte (manifest minus synced_at). */
export function check({ source = null, dest = DEFAULT_DEST } = {}) {
  const problems = verify(dest);
  const committed = JSON.parse(readFileSync(join(dest, MANIFEST), "utf8"));
  const tmp = mkdtempSync(join(tmpdir(), "gus-vendor-"));
  try {
    const fresh = sync({ commit: committed.upstream.commit, source, dest: tmp, syncedAt: committed.synced_at });
    if (JSON.stringify(fresh) !== JSON.stringify(committed)) problems.push(`${MANIFEST} differs from the pinned upstream`);
    for (const path of ALLOWLIST) {
      const a = join(dest, path);
      if (existsSync(a) && !readFileSync(a).equals(readFileSync(join(tmp, path)))) {
        problems.push(`${path} drifted from upstream ${committed.upstream.commit}`);
      }
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
  return [...new Set(problems)];
}

function main(argv) {
  const arg = (name) => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : null; };
  const source = arg("--source");
  const dest = arg("--dest") ? resolve(arg("--dest")) : DEFAULT_DEST;
  try {
    if (argv.includes("--verify") || argv.includes("--check")) {
      const problems = argv.includes("--check") ? check({ source, dest }) : verify(dest);
      if (problems.length) {
        console.error("vendored GUS runtime drifted from the pinned upstream:\n  - " + problems.join("\n  - "));
        return 1;
      }
      console.log(`vendored GUS runtime OK (${argv.includes("--check") ? "matches pinned upstream" : "matches manifest"})`);
      return 0;
    }
    const commit = arg("--from");
    const m = sync({ commit: requireSha(commit), source, dest });
    console.log(`synced ${m.files.length} files from ${m.upstream.repo}@${m.upstream.commit} (llama.cpp ${m.llama_cpp_commit})`);
    return 0;
  } catch (error) {
    console.error(error instanceof SyncError ? `sync-gus-runtime: ${error.message}` : error);
    return 1;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
